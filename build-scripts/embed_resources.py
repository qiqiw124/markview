#!/usr/bin/env python3
"""把 vendor JS/CSS + 原 markdown.css/template.html 全部嵌进二进制，避免 Bundle.module 路径依赖。"""
import pathlib, re

ROOT = pathlib.Path(__file__).parent.parent
RES = ROOT / "Sources" / "MarkView" / "Resources"
VENDOR = RES / "vendor"
OUT = ROOT / "Sources" / "MarkView" / "EmbeddedResources.swift"

def escape(s: str) -> str:
    # 反斜杠和 """ 转义；控制字符（除 \t \n \r）和 DEL 替换成空格，避免 Swift 编译器拒收
    s = s.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    return ''.join(c if (c >= ' ' and c != '\x7f' or c in '\t\n\r') else ' ' for c in s)

def embed(name: str, path: pathlib.Path) -> str:
    return f'/// {name}\nlet {name} = """\n{escape(path.read_text(encoding="utf-8"))}\n"""'

# 主 CSS + 模板
main_css = embed("embeddedMarkdownCSS", RES / "markdown.css")
main_html = embed("embeddedHTMLTemplate", RES / "template.html")

# highlight.js：core + 全部语言包
hl_files = [VENDOR / "highlight.min.js"] + sorted(VENDOR.glob("hl-*.min.js"))
hl_js = "\n".join(p.read_text(encoding="utf-8") for p in hl_files)
print(f"  highlight.js 共 {len(hl_files)} 个文件，合计 {len(hl_js)//1024} KB")

# highlight.js 主题：把 dark CSS 的每个选择器前缀 html.dark
def wrap_dark(css: str) -> str:
    """对每条 CSS 规则加 html.dark 前缀（保留 @media、@keyframes 块结构）。"""
    out = []
    i = 0
    while i < len(css):
        # 跳过空白
        m = re.search(r'\S', css[i:])
        if not m:
            break
        i += m.start()
        # 检查是否是 @ 规则（@media, @keyframes 等）
        if css[i] == '@':
            # 找到空格或 { 之前的内容
            brace = css.find('{', i)
            if brace < 0:
                out.append(css[i:])
                break
            at_name = css[i:brace].strip()
            # 找匹配的 }
            depth = 1
            j = brace + 1
            while j < len(css) and depth > 0:
                if css[j] == '{': depth += 1
                elif css[j] == '}': depth -= 1
                j += 1
            block = css[i:j]
            if at_name.startswith('@media'):
                # 把 @media 块内的选择器都加前缀
                inner = block[block.find('{')+1:block.rfind('}')]
                wrapped = wrap_dark(inner)
                out.append(at_name + '{' + wrapped + '}')
            else:
                # @keyframes 等直接保留
                out.append(block)
            i = j
        else:
            # 普通规则：找 { 之前的部分作为选择器组
            brace = css.find('{', i)
            if brace < 0:
                out.append(css[i:])
                break
            selectors = css[i:brace]
            # 找匹配的 }
            depth = 1
            j = brace + 1
            while j < len(css) and depth > 0:
                if css[j] == '{': depth += 1
                elif css[j] == '}': depth -= 1
                j += 1
            body = css[brace+1:j-1]
            # 给每个选择器加 html.dark 前缀
            new_selectors = []
            for sel in selectors.split(','):
                sel = sel.strip()
                if not sel: continue
                # 跳过 :root 之类的（dark 模式下不需要重新设置）
                if sel.startswith(':root'):
                    continue
                new_selectors.append('html.dark ' + sel)
            if new_selectors:
                out.append(',\n'.join(new_selectors) + ' {\n' + body + '\n}')
            i = j
    return '\n'.join(out)

light_css = (VENDOR / "hl-light.css").read_text(encoding="utf-8")
dark_css = (VENDOR / "hl-dark.css").read_text(encoding="utf-8")
hl_css = light_css + "\n/* === dark theme (auto-applied in dark mode) === */\n" + wrap_dark(dark_css)
print(f"  hl css 合计 {len(hl_css)//1024} KB")

# Mermaid
mermaid_js = (VENDOR / "mermaid.min.js").read_text(encoding="utf-8")
print(f"  mermaid {len(mermaid_js)//1024} KB")

# 生成
header = """// AUTO-GENERATED by build-scripts/embed_resources.py - do not edit.
// Resources embedded as string constants to avoid Bundle.module lookup at runtime.

"""
content = "\n\n".join([
    main_css,
    main_html,
    f'/// highlight.js bundled (core + languages)\nlet embeddedHighlightJS = """\n{escape(hl_js)}\n"""',
    f'/// highlight.js theme CSS (light + html.dark wrapped dark)\nlet embeddedHLCSS = """\n{escape(hl_css)}\n"""',
    f'/// Mermaid diagram renderer\nlet embeddedMermaidJS = """\n{escape(mermaid_js)}\n"""',
])

OUT.write_text(header + content, encoding="utf-8")
print(f"✅ {OUT} ({OUT.stat().st_size//1024} KB)")
